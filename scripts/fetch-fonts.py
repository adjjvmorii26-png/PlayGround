#!/usr/bin/env python3
"""Download the latin subset of the self-hosted variable fonts.

The generated files live in ``assets/fonts`` and are committed, so this script
only needs to run again when the font families or weights in ``styles.css``
change. Usage::

    scripts/fetch-fonts.py
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import urllib.request

CSS_URL = (
    "https://fonts.googleapis.com/css2"
    "?family=Barlow+Condensed:wght@600;700;800"
    "&family=Inter:wght@400..800"
    "&family=JetBrains+Mono:wght@400..700"
    "&display=swap"
)
UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/124.0 Safari/537.36"
)
OUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "assets" / "fonts"
LATIN_RANGE = "U+0000-00FF"

HEADER = """/* Self-hosted variable fonts (latin subset) - generated by scripts/fetch-fonts.py.
   Barlow Condensed (c) Jeremy Tribby, Inter (c) The Inter Project Authors,
   JetBrains Mono (c) JetBrains s.r.o. - all licensed under the SIL Open Font
   License 1.1 (https://scripts.sil.org/OFL). */

"""


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def main() -> None:
    css = fetch(CSS_URL).decode()
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    faces: list[str] = []
    for block in re.findall(r"@font-face\s*\{(.*?)\}", css, re.S):
        family = re.search(r"font-family: '([^']+)'", block)
        weight = re.search(r"font-weight: ([\d ]+);", block)
        src = re.search(r"url\((https://[^)]+)\)", block)
        unicode_range = re.search(r"unicode-range: ([^;]+);", block)
        if not (family and weight and src and unicode_range):
            continue
        if not unicode_range.group(1).strip().startswith(LATIN_RANGE):
            continue

        slug = family.group(1).lower().replace(" ", "-")
        weight_token = weight.group(1).strip().replace(' ', '-')
        filename = f"{slug}-{weight_token}-latin.woff2"
        (OUT_DIR / filename).write_bytes(fetch(src.group(1)))
        faces.append(
            "@font-face {{\n"
            "  font-family: '{family}';\n"
            "  font-style: normal;\n"
            "  font-weight: {weight};\n"
            "  font-display: swap;\n"
            "  src: url('./{filename}') format('woff2');\n"
            "  unicode-range: {unicode_range};\n"
            "}}".format(
                family=family.group(1),
                weight=weight.group(1).strip(),
                filename=filename,
                unicode_range=unicode_range.group(1).strip(),
            )
        )

    (OUT_DIR / "fonts.css").write_text(HEADER + "\n\n".join(faces) + "\n")
    print(f"wrote {len(faces)} @font-face rules to {OUT_DIR / 'fonts.css'}")


if __name__ == "__main__":
    main()
